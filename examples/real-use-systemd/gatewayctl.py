def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="install-service.sh", description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd")

    inst = sub.add_parser("install", help="build, install/update, and start the service")
    inst.add_argument("--no-build", dest="build", action="store_false",
                      help="skip cargo build and use the existing binary")
    inst.set_defaults(func=cmd_install, build=True)

    un = sub.add_parser("uninstall", help="stop and remove the service")
    un.add_argument("--purge", action="store_true", help="also remove installed files")
    un.add_argument("--yes", "-y", action="store_true", help="do not ask before deleting config")
    un.set_defaults(func=cmd_uninstall)

    sub.add_parser("status", help="systemctl status").set_defaults(func=cmd_status)
    sub.add_parser("restart", help="restart the service").set_defaults(func=cmd_restart)

    lg = sub.add_parser("logs", help="journalctl for the service")
    lg.add_argument("-n", "--lines", default=80)
    lg.add_argument("-f", "--follow", action="store_true")
    lg.set_defaults(func=cmd_logs)

    sec = sub.add_parser("secret", help="manage encrypted credentials")
    sec_sub = sec.add_subparsers(dest="secret_cmd", required=True)
    add = sec_sub.add_parser("add", help="add or replace a secret")
    add.add_argument("name")
    add.add_argument("value", nargs="?", help="omit to be prompted (keeps it out of shell history)")
    sec_sub.add_parser("list", help="list secret names (values are never printed)")
    rm = sec_sub.add_parser("rm", help="delete a secret")
    rm.add_argument("name")
    sec.set_defaults(func=cmd_secret)

    cfgp = sub.add_parser("config", help="manage config.jsonc")
    cfg_sub = cfgp.add_subparsers(dest="config_cmd", required=True)
    init = cfg_sub.add_parser("init", help="write config.jsonc from the template")
    init.add_argument("--force", action="store_true")
    init.set_defaults(func=cmd_config_init)
    cfg_sub.add_parser("show", help="print the config").set_defaults(func=cmd_show)
    cfg_sub.add_parser("path", help="print the config path").set_defaults(
        func=lambda a: (say(str(CONFIG_PATH)), 0)[1])

    sub.add_parser("doctor", help="check binary, config, secrets, service, desktop tools") \
        .set_defaults(func=cmd_doctor)

    t = sub.add_parser("test", help="run the hook by hand against a WAV file")
    t.add_argument("audio")
    t.set_defaults(func=cmd_test)
    return p


def main(argv: list[str]) -> int:
    parser = build_parser()
    # Bare invocation is the common case: install/update.
    args = parser.parse_args(argv or ["install"])
    if not hasattr(args, "func"):
        parser.print_help()
        return 2
    try:
        return args.func(args)
    except Fail as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        return 130


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
