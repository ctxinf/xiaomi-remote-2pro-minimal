def cmd_config_init(args: argparse.Namespace) -> int:
    CONFIG_PATH.parent.mkdir(parents=True, exist_ok=True)
    for template, destination in (("config.example.jsonc", CONFIG_PATH),
                                  ("hook.example.jsonc", HOOK_CONFIG_PATH)):
        if destination.exists() and not args.force:
            say(f"config already exists: {destination}  (--force to overwrite)")
            continue
        shutil.copy2(HERE / template, destination)
        destination.chmod(0o644)
        say(f"wrote {destination}")
    say("next:  ./install-service.sh secret add dashscope_api_key sk-xxxx")
    return 0


def cmd_install(args: argparse.Namespace) -> int:
    if not CONFIG_PATH.exists():
        cmd_config_init(argparse.Namespace(force=False))

    if args.build:
        manifest = REPO_ROOT / "Cargo.toml"
        say(f"==> cargo build --release ({manifest})")
        if not shutil.which("cargo"):
            raise Fail("cargo not found; install Rust or pass --no-build")
        proc = subprocess.run(["cargo", "build", "--release", "--manifest-path", str(manifest)])
        if proc.returncode != 0:
            raise Fail("cargo build failed")

    cfg = load_config()
    source_binary = which_binary(str(cfg.get("gateway", "binary", "auto")))

    # Stage a self-contained copy so the service no longer depends on the
    # checkout: `git clean`, a branch switch, or a moved repo must not break a
    # service that is already running.
    changed = []
    if source_binary.parent != INSTALL_BIN_DIR:
        if copy_if_changed(source_binary, INSTALL_BIN_DIR / source_binary.name):
            changed.append("binary")
    binary = INSTALL_BIN_DIR / source_binary.name

    for name in HOOK_FILES:
        if copy_if_changed(HERE / name, INSTALL_HOOK_DIR / name):
            changed.append(name)
    if write_if_changed(
        INSTALL_HOOK_DIR / "hooks.json",
        json.dumps({"hooks": {"start": ["./on_record.py"],
                              "end": ["./pipeline.py"]}}, indent=2) + "\n",
    ):
        changed.append("hooks.json")

    unit_name = f"{cfg.get('service', 'name', 'xiaomi-remote-gateway')}.service"
    unit_path = UNIT_DIR / unit_name
    unit_changed = write_if_changed(unit_path, unit_text(cfg, binary))
    if unit_changed:
        changed.append(unit_name)

    say(f"==> binary : {binary}")
    say(f"==> hooks  : {INSTALL_HOOK_DIR / 'on_record.py'} (start)")
    say(f"             {INSTALL_HOOK_DIR / 'pipeline.py'} (end)")
    say(f"==> config : {CONFIG_PATH}")
    say(f"==> unit   : {unit_path}")
    say(f"==> changed: {', '.join(changed) if changed else 'nothing (already up to date)'}")

    if cfg.missing_secrets:
        # Not fatal: the unit is still installed, it just cannot transcribe yet.
        say("")
        say("!! missing secrets — the hook will fail until these are set:")
        for name in sorted(set(cfg.missing_secrets)):
            say(f"     ./install-service.sh secret add {name} <value>")
        say("")

    # Hand the session's display/bus addresses to the user manager, or the hook
    # inherits an environment where wl-copy and notify-send have nothing to talk
    # to — the classic "works in the terminal, silent as a service" failure.
    session_vars = [v for v in ("WAYLAND_DISPLAY", "DISPLAY", "XDG_CURRENT_DESKTOP",
                                "XAUTHORITY") if os.environ.get(v)]
    if session_vars:
        systemctl("import-environment", *session_vars, check=False)

    systemctl("daemon-reload")
    if systemctl_out("is-enabled", unit_name) != "enabled":
        systemctl("enable", unit_name)
    active = systemctl_out("is-active", unit_name)
    if active != "active":
        systemctl("start", unit_name)
        say(f"==> started {unit_name}")
    elif changed:
        systemctl("restart", unit_name)
        say(f"==> restarted {unit_name}")
    else:
        say(f"==> {unit_name} already running with this configuration")

    # A user unit dies at logout unless lingering is on, which is rarely what
    # you want for something that follows your desktop session — so just say so.
    linger = Path(f"/var/lib/systemd/linger/{getpass.getuser()}").exists()
    if not linger:
        say("note: the service stops at logout. `sudo loginctl enable-linger "
            f"{getpass.getuser()}` to keep it running headless.")
    say(f"logs:  ./install-service.sh logs")
    return 0


def cmd_uninstall(args: argparse.Namespace) -> int:
    name = "xiaomi-remote-gateway"
    if CONFIG_PATH.exists():
        name = str(load_config(resolve_secrets=False).get("service", "name", name))
    unit_name = f"{name}.service"
    subprocess.run(["systemctl", "--user", "disable", "--now", unit_name],
                   check=False, text=True)
    (UNIT_DIR / unit_name).unlink(missing_ok=True)
    systemctl("daemon-reload", check=False)
    say(f"removed {UNIT_DIR / unit_name}")

    if args.purge:
        shutil.rmtree(DATA_DIR, ignore_errors=True)
        say(f"removed {DATA_DIR}")
        # Config and secrets are user data; deleting them needs a second ask.
        if args.yes or input(f"also delete {CONFIG_DIR} (config + secrets)? [y/N] ").lower() == "y":
            shutil.rmtree(CONFIG_DIR, ignore_errors=True)
            say(f"removed {CONFIG_DIR}")
    else:
        say(f"kept {DATA_DIR} and {CONFIG_DIR}  (--purge to remove)")
    return 0


def _unit_name() -> str:
    name = "xiaomi-remote-gateway"
    if CONFIG_PATH.exists():
        name = str(load_config(resolve_secrets=False).get("service", "name", name))
    return f"{name}.service"


def cmd_status(args: argparse.Namespace) -> int:
    return systemctl("status", "--no-pager", _unit_name(), check=False).returncode


def cmd_logs(args: argparse.Namespace) -> int:
    cmd = ["journalctl", "--user", "-u", _unit_name(), "-n", str(args.lines)]
    if args.follow:
        cmd.append("-f")
    return subprocess.run(cmd, check=False).returncode


def cmd_restart(args: argparse.Namespace) -> int:
    return systemctl("restart", _unit_name(), check=False).returncode


def cmd_secret(args: argparse.Namespace) -> int:
    store = SecretStore()
    if args.secret_cmd == "add":
        value = args.value
        if value is None:
            # No value on the command line means no credential in the shell
            # history and none in `ps` output either.
            value = getpass.getpass(f"value for {args.name}: ")
        if not value:
            raise Fail("empty value")
        store.set(args.name, value)
        say(f"stored {args.name} in {SECRETS_PATH} (encrypted, key: {SECRETS_KEY_PATH})")
        say("restart the service to pick it up: ./install-service.sh restart")
    elif args.secret_cmd == "list":
        names = store.names()
        if not names:
            say("(no secrets stored)")
        for name in names:
            say(name)
    elif args.secret_cmd == "rm":
        say(f"removed {args.name}" if store.remove(args.name) else f"no such secret: {args.name}")
    return 0


def cmd_show(args: argparse.Namespace) -> int:
    cfg = load_config(resolve_secrets=False)
    say(f"# {cfg.path}")
    say(cfg.path.read_text())
    return 0


def cmd_doctor(args: argparse.Namespace) -> int:
    ok = True

    def check(label: str, good: bool, hint: str = "") -> None:
        nonlocal ok
        say(f"[{'ok ' if good else 'FAIL'}] {label}" + (f"\n       {hint}" if not good and hint else ""))
        ok = ok and good

    check(f"python {sys.version_info.major}.{sys.version_info.minor} >= 3.11",
          sys.version_info >= (3, 11), "Python 3.11+ required")
    check("openssl present", shutil.which("openssl") is not None, "dnf install openssl")
    check(f"config {CONFIG_PATH}", CONFIG_PATH.exists(), "./install-service.sh config init")
    if not CONFIG_PATH.exists():
        return 1

    cfg = load_config()
    check("secrets resolved", not cfg.missing_secrets,
          "missing: " + ", ".join(sorted(set(cfg.missing_secrets))))
    try:
        check(f"binary {which_binary(str(cfg.get('gateway', 'binary', 'auto')))}", True)
    except Fail as e:
        check("gateway binary", False, str(e))
    check("unit installed", (UNIT_DIR / _unit_name()).exists(), "./install-service.sh install")
    active = systemctl_out("is-active", _unit_name())
    check(f"service active ({active or 'unknown'})", active == "active",
          "./install-service.sh logs")
    check("clipboard tool", any(shutil.which(c) for c in ("wl-copy", "xclip")),
          "dnf install wl-clipboard")
    check("notify-send", shutil.which("notify-send") is not None,
          "dnf install libnotify (optional)")

    usage = subprocess.run(["journalctl", "--user", "--disk-usage"],
                           capture_output=True, text=True).stdout.strip()
    if usage:
        # Not a pass/fail: journald enforces its own cap (SystemMaxUse, 10% of
        # the filesystem up to 4G by default). Just show where it stands.
        say(f"[info] journal: {usage}  (cap: journalctl --vacuum-size=500M to trim)")

    # keyd and the gateway both want the remote's exclusive grab; flag the
    # combination that silently does nothing.
    keyd = Path("/run/keyd.socket").exists()
    mode = str(cfg.get("gateway", "voice_key", "auto"))
    if keyd:
        say(f"[info] keyd is running; voice_key = \"{mode}\""
            + (" — the gateway will stand down and let keyd filter the mic key."
               if mode == "auto" else
               " — the gateway will fight keyd for the device; prefer \"auto\"."
               if mode == "always" else ""))
    return 0 if ok else 1


def cmd_test(args: argparse.Namespace) -> int:
    """Runs the hook exactly as the service would, against a WAV of your choice."""
    audio = Path(args.audio).expanduser().resolve()
    if not audio.is_file():
        raise Fail(f"no such file: {audio}")
    script = INSTALL_HOOK_DIR / "pipeline.py" if (INSTALL_HOOK_DIR / "pipeline.py").exists() \
        else HERE / "pipeline.py"
    env = {**os.environ, "XIAOMI_EVENT": "end", "XIAOMI_AUDIO_FILE": str(audio),
           "XIAOMI_SAMPLE_RATE": "16000"}
    say(f"==> {script} {audio}")
    return subprocess.run([sys.executable, str(script)], env=env,
                          stdin=subprocess.DEVNULL, check=False).returncode


