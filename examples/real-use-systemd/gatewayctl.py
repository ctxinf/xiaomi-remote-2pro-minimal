#!/usr/bin/env python3
"""Installer/CLI for the real-use systemd deployment.

Usage goes through `./install-service.sh`, which is just a shim over this file.

Everything here is an *upsert*: running `install` twice is the same as running
it once, and running it after editing `config.jsonc` reconciles the unit with
the config. Nothing is written unless its content actually changed, so a
re-install of an unchanged deployment does not bounce the service.

    ./install-service.sh                       # build + install/update + start
    ./install-service.sh install --no-build    # reuse the existing binary
    ./install-service.sh secret add dashscope_api_key sk-xxxx
    ./install-service.sh status | logs | restart | uninstall
    ./install-service.sh doctor                # check the whole chain
    ./install-service.sh test ./some.wav       # run the hook by hand
"""

from __future__ import annotations

import argparse
import getpass
import json
import os
import shlex
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import (  # noqa: E402
    CONFIG_DIR, CONFIG_PATH, DATA_DIR, HERE, INSTALL_BIN_DIR, INSTALL_HOOK_DIR,
    HOOK_CONFIG_PATH, REPO_ROOT, SECRETS_KEY_PATH, SECRETS_PATH, Fail, SecretStore, load_config,
    which_binary,
)

UNIT_DIR = Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config") / "systemd/user"
HOOK_FILES = ("pipeline.py", "on_record.py", "common.py")


def say(msg: str) -> None:
    print(msg)


def systemctl(*args: str, check: bool = True) -> subprocess.CompletedProcess:
    proc = subprocess.run(["systemctl", "--user", *args], text=True)
    if check and proc.returncode != 0:
        # systemctl has already printed the real reason; a Python traceback on
        # top of it would only bury it.
        raise Fail(f"systemctl --user {' '.join(args)} failed ({proc.returncode})")
    return proc


def systemctl_out(*args: str) -> str:
    """Runs systemctl for its output; a non-zero exit is an answer, not a fault
    (`is-active` exits 3 for an inactive unit)."""
    return subprocess.run(["systemctl", "--user", *args],
                          capture_output=True, text=True).stdout.strip()


def write_if_changed(path: Path, content: str, mode: int = 0o644) -> bool:
    """Writes `content` only when it differs. Returns True if it changed."""
    if path.exists() and path.read_text() == content:
        path.chmod(mode)
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    path.chmod(mode)
    return True


def copy_if_changed(src: Path, dst: Path, mode: int = 0o755) -> bool:
    if dst.exists() and dst.stat().st_size == src.stat().st_size and \
            dst.read_bytes() == src.read_bytes():
        return False
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)
    dst.chmod(mode)
    return True


# ---------------------------------------------------------------------------
# Unit generation
# ---------------------------------------------------------------------------


def gateway_args(cfg) -> list[str]:
    gw = cfg.section("gateway")
    args = [
        "--hook-config", str(INSTALL_HOOK_DIR / "hooks.json"),
        "--voice-key", str(gw.get("voice_key", "auto")),
        "--gain", str(gw.get("gain_db", 0.0)),
        "--keep-hours", str(gw.get("keep_hours", 24)),
        "--keep-max", str(gw.get("keep_max", 100)),
    ]
    if gw.get("record_dir"):
        args += ["--record-dir", str(Path(str(gw["record_dir"])).expanduser())]
    if gw.get("device_name"):
        args += ["--device-name", str(gw["device_name"])]
    if gw.get("verbose"):
        args.append("-v")
    args += [str(a) for a in gw.get("extra_args", [])]
    return args


def unit_text(cfg, binary: Path) -> str:
    svc = cfg.section("service")
    exec_start = " ".join(shlex.quote(x) for x in [str(binary), *gateway_args(cfg)])
    return f"""\
# Generated by examples/real-use-systemd/install-service.sh — do not edit.
# Edit {CONFIG_PATH} and re-run the installer instead.
[Unit]
Description={svc.get('description')}
Documentation=file://{HERE / 'README.md'}
After=graphical-session.target

[Service]
Type=simple
ExecStart={exec_start}
Restart=always
RestartSec={int(svc.get('restart_sec', 5))}
Environment=XIAOMI_GATEWAY_CONFIG={CONFIG_PATH}
# Logs go to stderr, which means journald: no log file of our own, and no
# unbounded growth — journald vacuums by its own SystemMaxUse policy.
StandardOutput=journal
StandardError=journal
SyslogIdentifier={svc.get('name', 'xiaomi-remote-gateway')}
# The hook reaches wl-copy / notify-send through the session bus and display,
# which a user unit only sees if the session imported them into the user
# manager; the installer does that for you (systemctl --user import-environment).
NoNewPrivileges=yes
# No PrivateTmp: recordings land in $TMPDIR and the hook must see the same one.
PrivateTmp=no

[Install]
WantedBy=default.target
"""


